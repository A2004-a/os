impl Driver for TextConsole {
    fn name(&self) -> &'static str {
        "GOP Text Console"
    }

    fn probe(&mut self) -> Result<bool, DriverError> {
        let fb = get_driver();
        Ok(fb.width >= FONT_WIDTH && fb.height >= FONT_HEIGHT)
    }

    fn init(&mut self) -> Result<(), DriverError> {
        let fb = get_driver();
        if fb.width < FONT_WIDTH || fb.height < FONT_HEIGHT {
            self.state = DriverState::Error;
            return Err(DriverError::DeviceNotFound);
        }
        self.cols = fb.width / FONT_WIDTH;
        self.rows = fb.height / FONT_HEIGHT;
        self.cursor_col = 0;
        self.cursor_row = 0;
        self.fg_color = Color::NOVA_CYAN;
        self.bg_color = Color::NOVA_BLUE;
        self.state = DriverState::Initialized;
        Ok(())
    }

    fn start(&mut self) -> Result<(), DriverError> {
        self.cursor_col = 0;
        self.cursor_row = 0;
        self.state = DriverState::Running;
        Ok(())
    }

    fn stop(&mut self) -> Result<(), DriverError> {
        self.state = DriverState::Stopped;
        Ok(())
    }

    fn state(&self) -> DriverState {
        self.state
    }
}

impl TextConsole {
    pub fn write_char(&mut self, c: char) {
        if c == '\n' {
            self.newline();
            return;
        }
        if c == '\r' {
            self.cursor_col = 0;
            return;
        }
        if c == '\t' {
            self.cursor_col = (self.cursor_col + 4) & !3;
            if self.cursor_col >= self.cols {
                self.newline();
            }
            return;
        }

        self.draw_char_at(self.cursor_col, self.cursor_row, c, self.fg_color, self.bg_color);
        self.cursor_col += 1;
        if self.cursor_col >= self.cols {
            self.newline();
        }
    }

    pub fn write_str(&mut self, s: &str) {
        for c in s.chars() {
            self.write_char(c);
        }
    }

    fn newline(&mut self) {
        self.cursor_col = 0;
        self.cursor_row += 1;
        if self.cursor_row >= self.rows {
            self.scroll_up();
            self.cursor_row = self.rows.saturating_sub(1);
        }
    }

    fn scroll_up(&mut self) {
        let fb = get_driver();
        let scroll_pixels = (FONT_HEIGHT * fb.stride) as usize;
        let total_pixels = (fb.height * fb.stride) as usize;

        if scroll_pixels < total_pixels {
            unsafe {
                let base = fb.get_base_mut_ptr();
                core::ptr::copy(base.add(scroll_pixels), base, total_pixels - scroll_pixels);
                // Clear the newly exposed bottom row
                for i in (total_pixels - scroll_pixels)..total_pixels {
                    *base.add(i) = self.bg_color.raw;
                }
            }
        }
    }

    fn draw_char_at(&self, col: u32, row: u32, c: char, fg: Color, bg: Color) {
        let ascii = (c as u32).clamp(32, 126) - 32;
        let glyph_offset = (ascii * 16) as usize;
        let glyph = &FONT_8X16[glyph_offset..glyph_offset + 16];

        let fb = get_driver();
        let start_x = col * FONT_WIDTH;
        let start_y = row * FONT_HEIGHT;

        for (y_offset, &row_byte) in glyph.iter().enumerate() {
            let py = start_y + y_offset as u32;
            for bit in 0..8 {
                let px = start_x + bit as u32;
                let is_fg = (row_byte & (0x80 >> bit)) != 0;
                let color = if is_fg { fg } else { bg };
                fb.draw_pixel(px, py, color);
            }
        }
    }
}

impl super::framebuffer::FramebufferDriver {
    pub fn get_base_mut_ptr(&self) -> *mut u32 {
        self.base_ptr
    }
}

pub fn init() {
    let con = unsafe { &mut *addr_of_mut!(CONSOLE_DRIVER) };
    if let Ok(_) = con.init() {
        let _ = con.start();
        serial::write_str("[DRIVER 3/10] Text Console Driver active (");
        print_u64(con.cols as u64);
        serial::write_str("x");
        print_u64(con.rows as u64);
        serial::write_str(" text cells)\n");
    }
}

pub fn write_str(s: &str) {
    let con = unsafe { &mut *addr_of_mut!(CONSOLE_DRIVER) };
    con.write_str(s);
}

pub fn get_glyph_data(c: u8) -> &'static [u8] {
    let ascii = if c >= 32 && c <= 126 {
        (c - 32) as usize
    } else {
        (b'?' - 32) as usize
    };
    let offset = ascii * 16;
    &FONT_8X16[offset..offset + 16]
}

fn print_u64(mut n: u64) {
    if n == 0 {
        serial::write_str("0");
        return;
    }
    let mut buf = [0u8; 20];
    let mut i = 0;
    while n > 0 {
        buf[i] = b'0' + (n % 10) as u8;
        n /= 10;
        i += 1;
    }
    for j in (0..i).rev() {
        serial::write_byte(buf[j]);
    }
}
