pub fn get_glyph_data(c: u8) -> &'static [u8] {
    let ascii = if (32..=126).contains(&c) {
        (c - 32) as usize
    } else {
        (b'?' - 32) as usize
    };
    let offset = ascii * 16;
    &FONT_8X16[offset..offset + 16]
}

pub fn measure_text(text: &str) -> Size {
    Size::new(text.len() as u32 * FONT_WIDTH, FONT_HEIGHT)
}

pub fn draw_char(buf: &mut [u32], stride: u32, c: char, x: i32, y: i32, color: Color) {
    let buf_h = (buf.len() as u32) / stride;
    let byte_val = if (c as u32) < 128 { c as u8 } else { b'?' };
    let glyph = get_glyph_data(byte_val);

    for row in 0..16 {
        let py = y + row as i32;
        if py < 0 || (py as u32) >= buf_h {
            continue;
        }

        let row_bits = glyph[row];
        for bit in 0..8 {
            let px = x + bit as i32;
            if px < 0 || (px as u32) >= stride {
                continue;
            }

            if (row_bits & (0x80 >> bit)) != 0 {
                buf[(py as u32 * stride + px as u32) as usize] = color.0;
            }
        }
    }
}

pub fn draw_text(buf: &mut [u32], stride: u32, text: &str, mut x: i32, y: i32, color: Color) {
    for ch in text.chars() {
        if ch == '\n' {
            continue;
        }
        draw_char(buf, stride, ch, x, y, color);
        x += FONT_WIDTH as i32;
    }
}
